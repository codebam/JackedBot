#!/usr/bin/env node
// Embeds schema.sql as a TS module so the workerd test project can apply the REAL
// schema (the `?raw` Vite idiom is not inlined inside the Workers test pool).
//
//   node scripts/gen-test-schema.mjs          # write it
//   node scripts/gen-test-schema.mjs --check  # fail if stale
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'schema.sql');
const OUT = join(ROOT, 'tests', 'worker', 'schema.generated.ts');

const sql = readFileSync(SRC, 'utf8').replace(/\r\n/g, '\n');
// Backticks and ${} would break the template literal we embed into.
const escaped = sql.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');

const out = `// GENERATED by scripts/gen-test-schema.mjs from schema.sql — DO NOT EDIT.
// Checked for staleness by tests/unit/schema.test.ts.
export const SCHEMA_SQL = \`${escaped}\`;
export default SCHEMA_SQL;
`;

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : null;
  if (current === out) {
    console.log('tests/worker/schema.generated.ts is up to date ✔');
    process.exit(0);
  }
  console.error('STALE: tests/worker/schema.generated.ts does not match schema.sql.');
  console.error('Run: node scripts/gen-test-schema.mjs');
  process.exit(1);
}

writeFileSync(OUT, out);
console.log(`wrote tests/worker/schema.generated.ts (${out.length} bytes from ${sql.length} bytes of SQL)`);
